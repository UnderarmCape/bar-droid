# The phone's model shaders (BarDroidModelShader, docs/ENGINE-SIM.md) built into the engine: the engine's VFS has
# BAR's official base content, not the branch's, so ModelDrawerState.cpp includes them as C++ raw strings. Run after
# editing cont/base/springcontent/shaders/GLSL/Model*ProgGL4Mobile.glsl, then build.
#   embed-model-shaders.ps1 [-Source C:\Tools\BARANDROID\hailmary-work\recoil-shader]
param([string]$Source = "C:\Tools\BARANDROID\hailmary-work\recoil-shader")
$ErrorActionPreference = "Stop"
$glsl = Join-Path $Source "cont\base\springcontent\shaders\GLSL"
$out = Join-Path $Source "rts\Rendering\Common"
foreach ($p in @(@("ModelVertProgGL4Mobile.glsl", "BarDroidModelShaders.vert.inc"), @("ModelFragProgGL4Mobile.glsl", "BarDroidModelShaders.frag.inc"))) {
  $text = [IO.File]::ReadAllText((Join-Path $glsl $p[0])) -replace "`r", ""
  if ($text -notmatch 'void main\(\)') { throw "$($p[0]): the engine takes a source for a file name unless it has 'void main()'" }
  $inc = "// generated by bar-droid-engine tools/engine-sim/embed-model-shaders.ps1 from cont/base/springcontent/shaders/GLSL/$($p[0])`n" +
         "R`"BDGLSL($text)BDGLSL`"`n"
  [IO.File]::WriteAllText((Join-Path $out $p[1]), $inc, (New-Object Text.UTF8Encoding($false)))
  "$($p[1]): $($text.Length) chars"
}
